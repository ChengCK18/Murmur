-- Tenants, drones and telemetry (plan §7; guide step 2.5).

CREATE EXTENSION IF NOT EXISTS timescaledb;

-- v1 has a single default tenant; the ID is there so the platform can later
-- serve several customers without a data migration.
CREATE TABLE tenants (
    id         bigint      PRIMARY KEY,
    name       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO tenants (id, name) VALUES (1, 'default');

-- One row per drone. id is the platform drone ID used everywhere else; drone
-- IDs are unique across tenants. A drone is a (source address, system ID)
-- pair, as in internal/registry; src_addr changes when a restarted SITL is
-- rebound to its old ID.
CREATE TABLE drones (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  bigint      NOT NULL REFERENCES tenants (id),
    src_addr   text        NOT NULL, -- ip:port
    sys_id     smallint    NOT NULL,
    comp_id    smallint    NOT NULL DEFAULT 1,
    name       text,
    type       smallint,             -- MAV_TYPE from HEARTBEAT
    first_seen timestamptz NOT NULL,
    last_seen  timestamptz NOT NULL,
    UNIQUE (src_addr, sys_id)
);

-- One row per published MAVLink message. received_at is the ingester's clock
-- (latency is always measured with it); time_boot_ms is the drone's, which
-- counts from boot and drifts.
CREATE TABLE telemetry (
    tenant_id    bigint           NOT NULL,
    drone_id     bigint           NOT NULL,
    msg_type     text             NOT NULL, -- MAVLink name, e.g. GLOBAL_POSITION_INT
    received_at  timestamptz      NOT NULL,
    time_boot_ms bigint,                    -- uint32 on the wire
    sys_id       smallint         NOT NULL,
    comp_id      smallint         NOT NULL,
    seq          smallint         NOT NULL,
    -- Typed copies of the fields replay and the map need, so those queries do
    -- not read JSON. Set only on the message types that carry them.
    lat          double precision,          -- degrees
    lon          double precision,          -- degrees
    alt_m        real,                      -- above mean sea level
    rel_alt_m    real,                      -- above home
    speed_ms     real,                      -- ground speed
    heading_deg  real,
    battery_pct  smallint,
    payload      jsonb            NOT NULL
);

-- One-day chunks: retention then drops whole days, and with 7 days kept there
-- are about 8 chunks.
SELECT create_hypertable('telemetry', by_range('received_at', INTERVAL '1 day'));

-- Idempotent inserts: the consumer writes with ON CONFLICT DO NOTHING, so a
-- message redelivered after a consumer restart is stored once. TimescaleDB
-- requires unique indexes to include the time column; this one does.
CREATE UNIQUE INDEX telemetry_dedup ON telemetry (drone_id, msg_type, received_at);

-- Retention (plan §13, open item 2): 7 days of raw data, moved to the
-- columnstore (compressed) after 1 day.
ALTER TABLE telemetry SET (
    timescaledb.enable_columnstore = true,
    timescaledb.segmentby = 'drone_id',
    timescaledb.orderby = 'received_at DESC'
);
CALL add_columnstore_policy('telemetry', after => INTERVAL '1 day');
SELECT add_retention_policy('telemetry', drop_after => INTERVAL '7 days');
